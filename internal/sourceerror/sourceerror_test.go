func TestDescribeRepositoryFailures(t *testing.T) {
	maintenance := FromResponse(&http.Response{StatusCode: 503, Status: "503 Service Unavailable", Header: http.Header{}, Body: io.NopCloser(strings.NewReader(`<!-- Generated by maintenance --><html><title>GitHub Enterprise is currently down for maintenance</title><style>private-upstream-page</style></html>`))})
	if strings.Contains(maintenance.Error(), "html") || strings.Contains(maintenance.Error(), "private-upstream-page") {
		t.Fatal("upstream HTML escaped the response boundary")
	}
	cases := []struct {
		name      string
		err       error
		want      string
		transient bool
	}{
		{"wrapped timeout", &url.Error{Op: "Get", URL: "https://github.ibm.com/api/v3/pulls/160", Err: context.DeadlineExceeded}, "GitHub did not respond in time.", true},
		{"maintenance", fmt.Errorf("find installation: %w", maintenance), "GitHub is down for maintenance.", true},
		{"wrapped SSH stderr", fmt.Errorf("cannot access git@github.ibm.com:team/config.git: %w: fatal: Your administrators are performing scheduled maintenance.", errors.New("exit status 128")), "GitHub is down for maintenance.", true},
		{"SSH maintenance", errors.New(`cannot access git@github.ibm.com:AgentOps/devops.git at main: exit status 128: fatal: Your administrators are performing scheduled maintenance.`), "GitHub is down for maintenance.", true},
		{"bad permissions", &HTTPError{StatusCode: 403}, "GitHub access was denied. Check the App's repository permissions.", false},
		{"authentication", &HTTPError{StatusCode: 401}, "GitHub authentication failed. Check the connection credentials.", false},
		{"rate limit", &HTTPError{StatusCode: 403, RateLimited: true}, "GitHub's request limit has been reached.", true},
		{"gateway", &HTTPError{StatusCode: 502}, "GitHub is temporarily unavailable.", true},
		{"cancellation", fmt.Errorf("poll: %w", context.Canceled), "Polling was cancelled.", false},
		{"mixed errors", fmt.Errorf("scan: %w", errors.Join(maintenance, errors.New("configuration is missing spec"))), "configuration is missing spec", false},
	}
	for _, tt := range cases {
		t.Run(tt.name, func(t *testing.T) {
			got := Describe(tt.err)
			if got.Message != tt.want || got.Transient != tt.transient {
				t.Fatalf("got %+v, want %s transient=%v", got, tt.want, tt.transient)
			}
		})
	}
}
func TestRateLimitResetAndSafeMessage(t *testing.T) {
	now := time.Now()
	e := FromResponse(&http.Response{StatusCode: 403, Status: "403 Forbidden", Header: http.Header{"X-Ratelimit-Remaining": []string{"0"}, "Retry-After": []string{"120"}}, Body: io.NopCloser(strings.NewReader(`{"message":"API rate limit exceeded"}`))})
	f := Describe(e)
	if !f.Transient || f.RetryAt.Before(now.Add(119*time.Second)) {
		t.Fatalf("rate limit deadline lost: %+v", f)
	}
	message := Concise("cannot access https://user:secret@example.test/repo?token=secret\ncannot access https://user:secret@example.test/repo?token=secret\n<html>hidden</html>")
	if message != "cannot access https://example.test/repo" {
		t.Fatalf("unsafe or duplicated diagnostics: %s", message)
	}
}
